#!/bin/bash

clear

rm -f *.o 

echo "--------------------------------------------------------------------------------"
echo "Compiling X11 Source Code ..."
echo "--------------------------------------------------------------------------------"
gcc -c -o XWindow.o XWindow.c

echo
echo "--------------------------------------------------------------------------------"
echo "Linking Object Files and Creating Binary ..."
echo "--------------------------------------------------------------------------------"

gcc XWindow.o -o XWindow -lX11

echo
echo "--------------------------------------------------------------------------------"
echo "Launching Application ..."
echo "--------------------------------------------------------------------------------"
./XWindow


